"""Turn the generated data into the coverage page: what exists and what was verified."""

from __future__ import annotations

from typing import Dict, List

from .client import MONTHLY, ON_DEMAND, YEARLY
from .specs import type_key

MODES = (MONTHLY, YEARLY, ON_DEMAND)


def _mode_cell(types: List[dict], mode: str) -> str:
    """'verified/with plan' for one billing mode, or '-' when no resource type has it."""
    with_plan = [t for t in types if mode in t.get("modes", {})]
    if not with_plan:
        return "-"
    verified = sum(1 for t in with_plan if t["modes"][mode]["ok"])
    return f"{verified}/{len(with_plan)}"


def coverage(services: List[dict], verification: dict) -> dict:
    """Counts for the headline of the coverage page."""
    resource_types = verification.get("resource_types", {})
    statuses: Dict[str, int] = {}
    mismatches = 0
    for outcome in resource_types.values():
        statuses[outcome["status"]] = statuses.get(outcome["status"], 0) + 1
        for info in outcome.get("modes", {}).values():
            if info.get("matchesList") is False:
                mismatches += 1
    return {
        "services": len(services),
        "with_calculator": sum(1 for s in services if s["hasCalculator"]),
        "resource_types": len(resource_types),
        "specs": sum(t["specs"] for t in resource_types.values()),
        "statuses": statuses,
        "list_price_mismatches": mismatches,
    }


def render_services_page(services: List[dict], verification: dict) -> str:
    resource_types = verification.get("resource_types", {})
    stats = coverage(services, verification)
    status = stats["statuses"]
    lines = [
        "# Coverage",
        "",
        "Generated by `python3 -m hwprice docs` from `data/`. Do not edit by hand.",
        "",
        f"Data verified on **{verification.get('generated', 'unknown')}**.",
        "",
        f"- **{stats['services']}** services in the calculator menu "
        f"({stats['with_calculator']} with a calculator page).",
        f"- **{stats['resource_types']}** resource types and **{stats['specs']}** specs, "
        "as listed by Huawei's own product list.",
        f"- Resource types where the price endpoint answered a real request: "
        f"**{status.get('verified', 0)}** fully verified, **{status.get('partial', 0)}** partly, "
        f"**{status.get('unverified', 0)}** not verified, **{status.get('no-plans', 0)}** with no price plan.",
        f"- Verified answers whose price differs from the catalog list price: "
        f"**{stats['list_price_mismatches']}** (see \"Differences\" below).",
        "",
        "## How to read this",
        "",
        "A cell like `3/4` means: of the 4 resource types that have that billing mode, 3 were priced "
        "against the endpoint. `-` means no resource type of the service has it. The specs come from "
        "Huawei's own list; \"verified\" means that one or two specs of the resource type were priced "
        "for real, not that every spec was. See [updating.md](updating.md).",
        "",
        "| Category | Service | `--service` | Resource types | Specs | Monthly | Yearly | Pay-per-use |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for service in services:
        path = service["urlPath"]
        types = [
            resource_types[type_key(path, pair["resourceType"])]
            for pair in service["resourceTypes"]
            if type_key(path, pair["resourceType"]) in resource_types
        ]
        # Resource types that the product list has but the menu does not name.
        known = {type_key(path, p["resourceType"]) for p in service["resourceTypes"]}
        types += [t for key, t in resource_types.items() if key.startswith(f"{path}|") and key not in known]
        if not types:
            lines.append(f"| {service['category']} | {service['service']} | `{path}` | 0 | 0 | - | - | - |")
            continue
        lines.append(
            f"| {service['category']} | {service['service']} | `{path}` | {len(types)} | "
            f"{sum(t['specs'] for t in types)} | "
            + " | ".join(_mode_cell(types, mode) for mode in MODES) + " |"
        )

    failed = [(key, outcome) for key, outcome in sorted(resource_types.items())
              if outcome["status"] in ("unverified", "partial")]
    lines += ["", "## Not fully verified", ""]
    if not failed:
        lines.append("Every resource type with a price plan was verified.")
    else:
        lines += ["These could not be priced in at least one billing mode. They are listed, not hidden.", "",
                  "| Service | Resource type | Billing mode | Reason |", "|---|---|---|---|"]
        for key, outcome in failed:
            path, resource_type = key.split("|", 1)
            for mode, info in outcome["modes"].items():
                if not info["ok"]:
                    reason = str(info.get("reason", "")).replace("|", "/")[:110]
                    lines.append(f"| `{path}` | `{resource_type}` | {mode} | {reason} |")

    differences = []
    for key, outcome in sorted(resource_types.items()):
        for mode, info in outcome.get("modes", {}).items():
            if info.get("matchesList") is False:
                path, resource_type = key.split("|", 1)
                differences.append(
                    f"| `{path}` | `{resource_type}` | {mode} | `{info['spec']}` | "
                    f"{info['listPrice']} | {info['amount']} |")
    lines += ["", "## Differences from the catalog list price", ""]
    if not differences:
        lines.append("None.")
    else:
        lines += [
            "In the reference region the price endpoint should equal the catalog list price. These did not, "
            "usually because the product is priced by a size or unit that the verification request did not "
            "reproduce. Treat the template of these resource types with care.", "",
            "| Service | Resource type | Billing mode | Spec | Catalog list | Endpoint |",
            "|---|---|---|---|---:|---:|",
        ] + differences
    lines.append("")
    return "\n".join(lines)
